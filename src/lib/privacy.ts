// 커뮤니티 글·댓글의 실명/기관명 의심 표현 찾기 (등록 직전 한 번 더 확인용, 막지는 않음)
// 예: "새싹병원", "서울소아과의원", "김지은 선생님", "박쌤", "이OO 원장님"

// 기관: 이름 + 기관 종류가 붙어 있는 경우 (예: 새싹발달센터)
// (?<![가-힣]) = 낱말 첫머리부터만 봄 ("가져갔더니 선생님"의 '져갔더니'를 이름으로 보지 않게)
const PLACE = /(?<![가-힣A-Za-z0-9])([가-힣A-Za-z0-9]{2,})(병원|의원|소아과|정신과|한의원|클리닉|센터|복지관|어린이집|유치원|학원)/g;
// 사람: 1~4글자 이름(성만 써도) + 호칭 (예: 김지은 선생님, 박쌤)
const PERSON = /(?<![가-힣])([가-힣]{1,4})\s?(선생님|쌤|원장님|교수님|치료사님|치료사|의사|박사님)/g;

// 이름이 아닌 일반 표현은 제외 (예: "발달센터", "담임 선생님")
const GENERIC_PLACE = new Set([
  "발달", "치료", "상담", "언어치료", "놀이치료", "아동발달", "재활", "복지", "육아종합지원", "보건",
  "대학", "종합", "동네", "근처", "가까운", "다니는", "다니던", "지역", "구립", "시립", "국공립", "민간", "가정",
  "기관", "전문", "아동", "소아", "이비인후", "개인",
]);
const GENERIC_PERSON = new Set([
  "담임", "담당", "치료", "언어치료", "놀이치료", "감각통합", "상담", "센터", "병원", "어린이집", "유치원",
  "우리", "저희", "그", "이", "다른", "새로운", "예전", "처음", "같은", "좋은", "친절한", "무서운", "주치",
  "소아과", "의사", "원장", "교수", "선생", "많은", "어떤", "모든", "여러",
  // 한 글자 일반어 (성씨와 겹치는 '이·한'도 오탐이 더 많아 제외)
  "한", "새", "옛", "전", "저", "제", "각", "타", "두", "세", "별", "옆", "앞", "뒤",
]);

/** 의심 표현 목록 (중복 제거). 없으면 빈 배열 */
export function findIdentifyingTerms(text: string): string[] {
  const found = new Set<string>();
  const placeSpans: [number, number][] = [];
  for (const m of text.matchAll(PLACE)) {
    if (GENERIC_PLACE.has(m[1])) continue;
    found.add(m[0]);
    placeSpans.push([m.index, m.index + m[0].length]);
  }
  for (const m of text.matchAll(PERSON)) {
    // 기관명 끝부분을 이름으로 잘못 읽은 경우 제외 (예: "서울소아과의원 원장님")
    const inPlace = placeSpans.some(([s, e]) => m.index >= s && m.index < e);
    if (!inPlace && !GENERIC_PERSON.has(m[1])) found.add(m[0].replace(/\s+/g, " "));
  }
  return [...found];
}

